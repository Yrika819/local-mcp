"""E4-C DeepAI Code dogfooding driver.

Drives a *separate* GoalLatch MCP server process (built from this branch) over
real stdio JSON-RPC, in an isolated Git repository. Nothing here touches the
user's existing `localmcp` session or approval daemon: the session id is unique
and the state directory is namespaced by that id inside GoalLatch's own state
root.

The "model" is the DeepAI Code agent itself: the planner proposal and the
readonly evidence are generated by the agent from the host-issued request, then
submitted through the real MCP tool surface.
"""

import json
import os
import subprocess
import sys
import tempfile
import time
import uuid
from pathlib import Path

REPO_ROOT = Path(
    os.environ.get("LOCAL_MCP_REPO_ROOT", Path(__file__).resolve().parents[2])
)
_DEFAULT_BINARY = REPO_ROOT / "target" / "debug" / ("local-mcp.exe" if os.name == "nt" else "local-mcp")
BINARY = Path(os.environ.get("LOCAL_MCP_BINARY", _DEFAULT_BINARY))
_WORK_ROOT = Path(
    os.environ.get("LOCAL_MCP_E4C_WORK", Path(tempfile.gettempdir()) / "gl-e4c-dogfood")
)
WORK = _WORK_ROOT / time.strftime("%Y%m%d-%H%M%S")


class McpClient:
    def __init__(self, cwd: Path):
        self.proc = subprocess.Popen(
            [str(BINARY), "mcp"],
            cwd=str(cwd),
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            bufsize=1,
        )
        self.next_id = 0
        self.initialize()

    def _read_frame(self):
        while True:
            line = self.proc.stdout.readline()
            if not line:
                err = self.proc.stderr.read()
                raise RuntimeError(f"MCP server closed stdout: {err}")
            line = line.strip()
            if not line:
                continue
            return json.loads(line)

    def request(self, method: str, params=None):
        self.next_id += 1
        frame = {"jsonrpc": "2.0", "id": self.next_id, "method": method}
        if params is not None:
            frame["params"] = params
        self.proc.stdin.write(json.dumps(frame) + "\n")
        self.proc.stdin.flush()
        while True:
            response = self._read_frame()
            if response.get("id") == self.next_id:
                if "error" in response:
                    raise RuntimeError(f"{method} failed: {response['error']}")
                return response["result"]

    def initialize(self):
        return self.request("initialize", {})

    def call(self, name: str, arguments: dict):
        result = self.request("tools/call", {"name": name, "arguments": arguments})
        content = result.get("content") or []
        texts = [item.get("text", "") for item in content if item.get("type") == "text"]
        payload = texts[0] if texts else ""
        try:
            parsed = json.loads(payload)
        except json.JSONDecodeError:
            parsed = {"raw": payload}
        return {"is_error": bool(result.get("isError")), "body": parsed}

    def close(self):
        try:
            self.proc.stdin.close()
        except Exception:
            pass
        try:
            self.proc.wait(timeout=30)
        except subprocess.TimeoutExpired:
            self.proc.kill()


def run(argv, cwd=None):
    return subprocess.run(argv, cwd=cwd, capture_output=True, text=True)


def prepare_repo(root: Path) -> Path:
    repo = root / "repo"
    repo.mkdir(parents=True)
    (repo / "inventory.txt").write_text(
        "line-1: alpha\nline-2: beta\nline-3: gamma\nMARKER=E4C-DOGFOOD-OK\n",
        encoding="utf-8",
    )
    (repo / "README.md").write_text("# isolated e4c dogfood repo\n", encoding="utf-8")
    run(["git", "init", "-q"], cwd=repo)
    run(["git", "add", "."], cwd=repo)
    run(
        [
            "git",
            "-c",
            "user.email=e4c@example.invalid",
            "-c",
            "user.name=e4c dogfood",
            "commit",
            "-q",
            "-m",
            "seed",
        ],
        cwd=repo,
    )
    return repo


def create_session(repo: Path, session_id: str):
    """Create (not replace) one fresh GoalLatch session bound to the repo."""
    # `start` registers the session and then exits on stdin EOF; approvals are
    # never requested by the goal_* tools, so no daemon needs to stay up.
    proc = subprocess.run(
        [str(BINARY), "start", session_id],
        cwd=str(repo),
        input="",
        capture_output=True,
        text=True,
        timeout=60,
    )
    if "local-mcp session:" not in (proc.stderr + proc.stdout):
        raise RuntimeError(f"session creation failed: {proc.stderr}")


def git_state(repo: Path) -> str:
    return run(["git", "status", "--porcelain"], cwd=repo).stdout


def sha256_text(text: str) -> str:
    import hashlib

    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def planner_proposal(work: dict, evidence_requirement: str) -> dict:
    """The agent's plan, derived only from the host-issued request."""
    request = work["request"]
    criterion_ids = [c["criterion_id"] for c in request["completion_criteria"]]
    return {
        "goal_id": work["goal_id"],
        "goal_revision": work["goal_revision"],
        "summary": "Read-only inventory inspection with host-verifiable evidence",
        "tasks": [
            {
                "proposal_id": "inspect-inventory",
                "title": "Inspect inventory.txt read-only",
                "objective": (
                    "Read inventory.txt inside the Goal workspace and report the "
                    "marker line as structured evidence"
                ),
                "mandatory": True,
                "worker": "CODEX_READONLY",
                "dependencies": [],
                "scope": {
                    "allowed_paths": ["inventory.txt"],
                    "forbidden_paths": [],
                    "operation_kind": "READ_ONLY",
                    "replay_safety": "SAFE_READ_ONLY",
                },
                "verification": [
                    {"kind": "STRUCTURED_EVIDENCE", "requirement_id": evidence_requirement}
                ],
            }
        ],
        "criterion_bindings": [
            {"criterion_id": criterion_id, "task_refs": ["inspect-inventory"]}
            for criterion_id in criterion_ids
        ],
    }


def readonly_answer(work: dict, marker_line: str, evidence_requirement: str) -> dict:
    """The agent's investigation result, grounded in the file it actually read."""
    request = work["request"]
    return {
        "goal_id": request["goal_id"],
        "task_id": request["task_id"],
        "attempt_id": request["attempt_id"],
        "goal_revision": request["goal_revision"],
        "plan_revision": request["plan_revision"],
        "status": "candidate_complete",
        "summary": "Read inventory.txt read-only and extracted the marker line",
        "evidence": [
            {
                "kind": evidence_requirement,
                "value": f"inventory.txt contains {marker_line.strip()}",
            }
        ],
    }


def submit_args(session_id: str, goal_id: str, work: dict, submission_id: str, response: dict) -> dict:
    return {
        "session_id": session_id,
        "goal_id": goal_id,
        "work_id": work["work_id"],
        "submission_id": submission_id,
        "expected_goal_revision": work["goal_revision"],
        "request_digest": work["request_digest"],
        "response": response,
    }


def main() -> int:
    report = {"experiments": {}}
    repo = prepare_repo(WORK)
    session_id = f"e4c-dogfood-{uuid.uuid4().hex[:8]}"
    create_session(repo, session_id)
    report["session_id"] = session_id
    report["repo"] = str(repo)
    report["workspace_before"] = git_state(repo)

    # --- Experiment 1: Readonly Goal end to end -----------------------------
    client = McpClient(repo)
    try:
        info = client.call("session_info", {"session_id": session_id})
        reported_cwd = str(info["body"]["cwd"]).removeprefix("\\\\?\\")
        assert Path(reported_cwd) == repo.resolve(), info
        started = client.call(
            "goal_start",
            {
                "session_id": session_id,
                "objective": (
                    "Inspect inventory.txt in this isolated repository and submit "
                    "host-verifiable structured evidence"
                ),
                "completion_criteria": [
                    "inventory.txt was inspected read-only and its marker line is reported"
                ],
                "model_backend": "EXTERNAL",
            },
        )
        assert not started["is_error"], started
        goal_id = started["body"]["goal_id"]

        next1 = client.call("goal_next", {"session_id": session_id, "goal_id": goal_id})
        assert next1["body"]["outcome"] == "MODEL_REQUIRED", next1
        planner_work = next1["body"]["model_work"]
        assert planner_work["role"] == "PLANNER"

        proposal = planner_proposal(planner_work, "inventory-marker")
        planned = client.call(
            "goal_submit",
            submit_args(session_id, goal_id, planner_work, str(uuid.uuid4()), proposal),
        )
        assert planned["body"]["outcome"] == "COMMITTED", planned
        assert planned["body"]["code"] == "PLAN_APPLIED", planned

        next2 = client.call("goal_next", {"session_id": session_id, "goal_id": goal_id})
        assert next2["body"]["outcome"] == "MODEL_REQUIRED", next2
        readonly_work = next2["body"]["model_work"]
        assert readonly_work["role"] == "READONLY", readonly_work

        read = client.call(
            "read_file", {"session_id": session_id, "path": "inventory.txt"}
        )
        assert not read["is_error"], read
        marker_line = [
            line for line in read["body"]["raw"].splitlines() if line.startswith("MARKER=")
        ][0]

        answer = readonly_answer(readonly_work, marker_line, "inventory-marker")
        inspected = client.call(
            "goal_submit",
            submit_args(session_id, goal_id, readonly_work, str(uuid.uuid4()), answer),
        )
        assert inspected["body"]["outcome"] == "COMMITTED", inspected
        assert inspected["body"]["code"] == "READONLY_CANDIDATE_COMPLETE", inspected

        next3 = client.call("goal_next", {"session_id": session_id, "goal_id": goal_id})
        assert next3["body"]["outcome"] == "HOST_PROGRESS", next3
        assert next3["body"]["status"] == "COMPLETED", next3

        result = client.call("goal_result", {"session_id": session_id, "goal_id": goal_id})
        assert result["body"]["result_kind"] == "COMPLETED", result

        report["experiments"]["readonly_goal"] = {
            "goal_id": goal_id,
            "planner_outcome": planned["body"]["outcome"],
            "readonly_outcome": inspected["body"]["outcome"],
            "final_outcome": next3["body"]["outcome"],
            "final_status": next3["body"]["status"],
            "host_steps_on_final_call": next3["body"]["host_steps_executed"],
            "goal_result": result["body"]["result_kind"],
            "plan_revision": next3["body"]["plan_revision"],
            "revision": next3["body"]["revision"],
        }
    finally:
        client.close()

    report["workspace_after_experiment_1"] = git_state(repo)
    return report, repo, session_id


if __name__ == "__main__":
    out, repo, session_id = main()
    print(json.dumps(out, indent=2, ensure_ascii=False))
